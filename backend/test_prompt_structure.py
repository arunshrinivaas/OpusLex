CAPTURED_PROMPTS: list[str] = []

def _mock_search(db, query, limit, distance_threshold=0.80, document_ids=None, user_id=None, **kwargs):
    if document_ids and 25 in document_ids:
        return [{"document_id": 25, "document_title": "Doc 25", "document_filename": "doc25.pdf",
                 "chunk_index": i, "content": f"content-25-{i}", "distance": 0.20} for i in range(4)]
    if document_ids and 23 in document_ids:
        return [{"document_id": 23, "document_title": "Doc 23", "document_filename": "doc23.pdf",
                 "chunk_index": 0, "content": "content-23-0", "distance": 0.35}]
    if document_ids and 27 in document_ids:
        return []  # 0 chunks — the problem case
    if document_ids and 99 in document_ids:
        return [{"document_id": 99, "document_title": "Doc 99", "document_filename": "doc99.pdf",
                 "chunk_index": 0, "content": "content-99-0", "distance": 0.40}]
    return []

async def _capturing_copilot(question, context, **kwargs):
    CAPTURED_PROMPTS.append(question)
    return "[MOCK LLM RESPONSE]"

rag_mod.search_similar_chunks = _mock_search
rag_mod.ask_copilot_with_context = _capturing_copilot

from app.services.rag_service import compare_documents


# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------

async def run_comparison(docs, question="Compare these documents") -> str:
    CAPTURED_PROMPTS.clear()
    original_search = rag_mod.search_similar_chunks
    original_ask = rag_mod.ask_copilot_with_context
    rag_mod.search_similar_chunks = _mock_search
    rag_mod.ask_copilot_with_context = _capturing_copilot
    try:
        await compare_documents(db=None, question=question, documents=docs, limit=5)
    finally:
        rag_mod.search_similar_chunks = original_search
        rag_mod.ask_copilot_with_context = original_ask
    assert CAPTURED_PROMPTS, "No prompt was captured — ask_copilot_with_context not called"
    return CAPTURED_PROMPTS[-1]


