"""
LLM Provider abstraction.

Supports:
  - MockLLMProvider  : deterministic, no external deps (used in DEMO_MODE)
  - OllamaLLMProvider: calls local Ollama instance

The active provider is chosen by the LLM_PROVIDER env var:
  LLM_PROVIDER=mock    → MockLLMProvider
  LLM_PROVIDER=ollama  → OllamaLLMProvider
"""

from __future__ import annotations

import asyncio
import json
import logging
import textwrap
from abc import ABC, abstractmethod
from typing import Any

import httpx

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Base interface
# ---------------------------------------------------------------------------


class LLMProvider(ABC):
    """Abstract LLM provider interface."""

    @abstractmethod
    async def generate(self, prompt: str, system: str | None = None) -> str:
        """Generate a response for a given prompt."""
        ...

    @abstractmethod
    async def stream(self, prompt: str, system: str | None = None):
        """Yield tokens as they are generated."""
        ...

    async def structured_output(
        self,
        prompt: str,
        schema: dict[str, Any],
        system: str | None = None,
    ) -> dict[str, Any]:
        """
        Request a JSON-structured response.
        Default implementation: generate → JSON parse.
        Override in subclasses for native structured output support.
        """
        json_prompt = (
            f"{prompt}\n\nRespond ONLY with valid JSON matching this schema:\n"
            f"{json.dumps(schema, indent=2)}"
        )
        raw = await self.generate(json_prompt, system=system)
        # Strip markdown fences if present
        raw = raw.strip()
        if raw.startswith("```"):
            raw = raw.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
        try:
            return json.loads(raw)
        except json.JSONDecodeError:
            logger.warning("LLM did not return valid JSON; returning raw text")
            return {"raw": raw}


