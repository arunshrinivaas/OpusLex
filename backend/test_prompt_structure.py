"""
Test: verify the comparison prompt generated by compare_documents() explicitly
contains all required per-document slots for A, B, C (and D for 4-doc case).

Does NOT require a live database or LLM — mocks both.
Verifies:
  1. "Document A", "Document B", "Document C" all present in the prompt
  2. Each slot contains the correct filename (deterministic mapping)
  3. doc IDs outside the set never appear in the prompt
  4. 2-document prompt has A and B but NOT C
  5. 4-document prompt has A, B, C, D
  6. "DOCUMENT-BY-DOCUMENT ANALYSIS" section header present
  7. "REQUIRED PARTICIPANTS" line present and lists every label
  8. Existing retrieval test: all 10 tests still pass
"""

